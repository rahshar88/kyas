import { createClient, type SupabaseClient } from '@supabase/supabase-js';

import { env } from '@/config/env';

import { secureSessionStore } from './secure-session-store';

/**
 * The single Supabase client.
 *
 * §4.3: the app "must access backend capabilities through typed service interfaces so
 * individual vendors can be changed later without rewriting screens". So this module is the
 * only place `@supabase/supabase-js` is imported outside the repositories — screens never
 * see it, and swapping the vendor means rewriting the repositories, not the UI.
 *
 * The session lives in the platform keychain via `secureSessionStore`, per §13.1's
 * "SecureStore for refresh/session secrets". That adapter chunks the value because a
 * Supabase session exceeds SecureStore's practical per-value size — see its own comments.
 */
/**
 * Hand-written schema types, mirroring supabase/migrations.
 *
 * Not generated by `supabase gen types`, because that needs a live project and Milestone 1
 * has none yet. The shape below is what supabase-js expects — each table needs `Row`,
 * `Insert`, `Update` and `Relationships`, and the schema needs `Views`, `Functions`, `Enums`
 * and `CompositeTypes` — otherwise query results infer as `never` and every field access
 * fails to compile.
 *
 * Replace this file with generated types once a Supabase project exists.
 */
type ProfileRow = {
  user_id: string;
  display_name: string | null;
  avatar_path: string | null;
  status: string;
  onboarding_version: number;
  created_at: string;
  updated_at: string;
};

type StudentProfileRow = {
  user_id: string;
  provider: string | null;
  provider_other: string | null;
  campus: string | null;
  course: string | null;
  study_level: string | null;
  intake_month: number | null;
  intake_year: number | null;
  completion_month: number | null;
  completion_year: number | null;
  student_email: string | null;
  suburb: string | null;
  postcode: string | null;
  arrival_status: string | null;
  india_state_code: string | null;
  hometown: string | null;
  created_at: string;
  updated_at: string;
  /** §S10 'prefer not to specify'. Distinct from 'none selected yet'. */
  communities_not_specified: boolean;
};

type IndiaStateRow = {
  code: string;
  name: string;
  is_union_territory: boolean;
  sort_order: number;
  active: boolean;
};

type EducationProviderRow = {
  code: string;
  name: string;
  city: string | null;
  sort_order: number;
  active: boolean;
};

/** Milestone 2 rows (§11.1). Catalogues share one shape, so they share one type. */
type CatalogueRow = {
  code: string;
  label: string;
  active: boolean;
  sort_order: number;
};

/**
 * §S04. A student may read their own redemption row and nothing else — that single fact is
 * what tells the launch screen whether to resume registration or ask for an invitation.
 */
type InviteRedemptionRow = {
  invite_id: string;
  user_id: string;
  redeemed_at: string;
};

type LanguageRow = { code: string; name: string; active: boolean; sort_order: number };

type ProfileLanguageRow = {
  user_id: string;
  language_code: string;
  proficiency: 'native' | 'fluent' | 'conversational' | 'learning';
};

type ProfileCodeRow = { user_id: string; code: string };
type ProfileGoalRow = { user_id: string; goal_code: string; rank: number };

type ProfileVisibilityRow = {
  user_id: string;
  show_suburb: boolean;
  show_india_state: boolean;
  show_hometown: boolean;
  show_languages: boolean;
  show_communities: boolean;
  show_study: boolean;
};

type ConsentRow = {
  id: string;
  user_id: string;
  policy_type: 'terms' | 'privacy' | 'community_guidelines' | 'beta_changes' | 'marketing';
  version: string;
  accepted: boolean;
  accepted_at: string;
};

type VerificationRequestRow = {
  id: string;
  user_id: string;
  state: 'pending' | 'approved' | 'rejected' | 'withdrawn';
  submitted_at: string;
  reviewed_at: string | null;
  rejection_category:
    | 'not_eligible'
    | 'incomplete_information'
    | 'unable_to_verify_study'
    | 'duplicate_account'
    | 'safety_concern'
    | 'other'
    | null;
};

