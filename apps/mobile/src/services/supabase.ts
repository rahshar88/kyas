export type KyaSceneSupabaseClient = SupabaseClient<Database>;

let client: KyaSceneSupabaseClient | undefined;

export function getSupabase(): KyaSceneSupabaseClient {
  client ??= createClient<Database>(
    env.EXPO_PUBLIC_SUPABASE_URL,
    env.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
    {
      auth: {
        storage: secureSessionStore,
        autoRefreshToken: true,
        persistSession: true,
        // React Native has no URL to parse a callback out of; email OTP does not use one.
        detectSessionInUrl: false,
      },
    },
  );

  return client;
}

/** Test seam. Lets a test inject a fake without reaching into module state. */
export function __setSupabaseClientForTests(next: KyaSceneSupabaseClient | undefined): void {
  client = next;
}
